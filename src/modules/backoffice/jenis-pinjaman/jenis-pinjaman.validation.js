import { z } from "zod";

export const queryJenisPinjamanSchema = z.object({
  search: z.string().optional(),
  status: z.enum(["all", "active", "inactive"]).default("all"),
});

export const createJenisPinjamanSchema = z.object({
  kode: z.string().max(20, "Kode maksimal 20 karakter").optional().nullable().or(z.literal("")),
  nama: z.string().min(3, "Nama minimal 3 karakter").max(100, "Nama maksimal 100 karakter"),
  metode_bunga: z.string().optional(),
  metodeBunga: z.string().optional(),
  tipeBunga: z.string().optional(),
  suku_bunga_tahunan: z.coerce.number().min(0).max(100).optional(),
  sukuBungaTahunan: z.coerce.number().min(0).max(100).optional(),
  sukuBunga: z.coerce.number().min(0).max(100).optional(),
  tenor_min_bulan: z.coerce.number().min(1).default(1),
  tenorMinBulan: z.coerce.number().min(1).optional(),
  tenor_max_bulan: z.coerce.number().min(1).default(60),
  tenorMaxBulan: z.coerce.number().min(1).optional(),
  tenorMaksimal: z.coerce.number().min(1).optional(),
  plafon_min: z.coerce.number().min(0).default(500000),
  plafonMin: z.coerce.number().min(0).optional(),
  plafon_max: z.coerce.number().min(0).default(100000000),
  plafonMax: z.coerce.number().min(0).optional(),
  biaya_admin_persen: z.coerce.number().min(0).max(100).default(1),
  biayaAdminPersen: z.coerce.number().min(0).max(100).optional(),
  biayaAdmin: z.coerce.number().min(0).max(100).optional(),
  denda: z.coerce.number().optional(),
  deskripsi: z.string().optional().nullable(),
  is_active: z.boolean().default(true),
  isActive: z.boolean().optional(),
  status: z.string().optional(),
});

export const updateJenisPinjamanSchema = z.object({
  kode: z.string().max(20).optional().nullable().or(z.literal("")),
  nama: z.string().min(3).max(100).optional(),
  metode_bunga: z.string().optional(),
  metodeBunga: z.string().optional(),
  tipeBunga: z.string().optional(),
  suku_bunga_tahunan: z.coerce.number().min(0).max(100).optional(),
  sukuBungaTahunan: z.coerce.number().min(0).max(100).optional(),
  sukuBunga: z.coerce.number().min(0).max(100).optional(),
  tenor_min_bulan: z.coerce.number().min(1).optional(),
  tenorMinBulan: z.coerce.number().min(1).optional(),
  tenor_max_bulan: z.coerce.number().min(1).optional(),
  tenorMaxBulan: z.coerce.number().min(1).optional(),
  tenorMaksimal: z.coerce.number().min(1).optional(),
  plafon_min: z.coerce.number().min(0).optional(),
  plafonMin: z.coerce.number().min(0).optional(),
  plafon_max: z.coerce.number().min(0).optional(),
  plafonMax: z.coerce.number().min(0).optional(),
  biaya_admin_persen: z.coerce.number().min(0).max(100).optional(),
  biayaAdminPersen: z.coerce.number().min(0).max(100).optional(),
  biayaAdmin: z.coerce.number().min(0).max(100).optional(),
  denda: z.coerce.number().optional(),
  deskripsi: z.string().optional().nullable(),
  is_active: z.boolean().optional(),
  isActive: z.boolean().optional(),
  status: z.string().optional(),
});
